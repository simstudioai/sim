/**
 * Embeds the files a bundled consumer such as the CLI writes into a source directory without the
 * package on disk, each as a string (or, for a folder, a path → text record) in
 * `src/codegen/*.generated.ts`: `src/core.d.ts` as `CORE_DTS` (the authoring declarations),
 * `cookbook/workflow.ts` as `COOKBOOK_TS` (the example workflow), the workspace declaration SDK
 * `src/workspace/*.d.ts` as `WORKSPACE_SDK_DTS`, and the example workspace directory
 * `cookbook/workspace/**` as `WORKSPACE_COOKBOOK`. `core-text.test.ts`, `cookbook-text.test.ts`
 * and `workspace-text.test.ts` fail when any drifts.
 *
 *   bun scripts/generate-embedded-text.ts && bunx biome check --write src/codegen
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')

interface Embedded {
  source: string
  target: string
  name: string
  doc: string
  /** For a folder: which of its files are embedded, by path relative to it. */
  files?: { recursive: boolean; include: (file: string) => boolean }
}

const EMBEDDED: Embedded[] = [
  {
    source: 'src/core.d.ts',
    target: 'src/codegen/core-text.generated.ts',
    name: 'CORE_DTS',
    doc: 'The text of `core.d.ts`, the workflow SDK authoring declarations.',
  },
  {
    source: 'cookbook/workflow.ts',
    target: 'src/codegen/cookbook-text.generated.ts',
    name: 'COOKBOOK_TS',
    doc: 'The text of `cookbook/workflow.ts`: one correct example of each common block.',
  },
  {
    source: 'src/workspace',
    target: 'src/codegen/workspace-text.generated.ts',
    name: 'WORKSPACE_SDK_DTS',
    doc: 'The workspace declaration SDK, file name → text (`index.d.ts` re-exports the rest).',
    files: { recursive: false, include: (file) => file.endsWith('.d.ts') },
  },
  {
    source: 'cookbook/workspace',
    target: 'src/codegen/workspace-cookbook-text.generated.ts',
    name: 'WORKSPACE_COOKBOOK',
    doc: 'The example workspace directory, path → text: one resource of each kind and a workflow using them.',
    files: { recursive: true, include: () => true },
  },
]

/** A folder's embedded files, by `/`-separated path relative to it, in path order. */
function folderTexts(dir: string, files: NonNullable<Embedded['files']>): Record<string, string> {
  return Object.fromEntries(
    readdirSync(dir, { recursive: files.recursive, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => path.relative(dir, path.join(entry.parentPath, entry.name)))
      .map((file) => file.split(path.sep).join('/'))
      .filter(files.include)
      .sort()
      .map((file) => [file, readFileSync(path.join(dir, file), 'utf8')])
  )
}

for (const { source, target, name, doc, files } of EMBEDDED) {
  const absolute = path.join(packageRoot, source)
  const declaration = files
    ? `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(folderTexts(absolute, files))}`
    : `export const ${name} = ${JSON.stringify(readFileSync(absolute, 'utf8'))}`
  writeFileSync(
    path.join(packageRoot, target),
    [
      `// Generated by scripts/generate-embedded-text.ts from ${source}; do not edit.`,
      '',
      `/** ${doc} */`,
      declaration,
      '',
    ].join('\n')
  )
}
