/**
 * Embeds the files a bundled consumer such as the CLI writes into a source directory without the
 * package on disk, each as a string (or, for a folder, a path → text record) in
 * `src/codegen/*.generated.ts`: `src/core.d.ts` as `CORE_DTS` (the authoring declarations),
 * `cookbook/examples/*.ts` as `COOKBOOK_EXAMPLES` (the example workflows), the workspace declaration SDK
 * `src/workspace/*.d.ts` as `WORKSPACE_SDK_DTS`, and the example workspace directory
 * `cookbook/workspace/**` as `WORKSPACE_COOKBOOK`. The output is written as generated (biome
 * skips these files), so `--check` (run by `check:audits`) compares it byte for byte.
 *
 *   bun run generate:workflow-sdk-embedded-text
 *   bun run check:workflow-sdk-embedded-text
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { type EmbeddedFolder, embeddedFolderTexts } from '../src/codegen/embedded-files'

const packageRoot = path.resolve(import.meta.dirname, '..')

interface Embedded {
  source: string
  target: string
  name: string
  doc: string
  /** For a folder: which of its files are embedded, by path relative to it (never a dotfile). */
  files?: EmbeddedFolder
}

const EMBEDDED: Embedded[] = [
  {
    source: 'src/core.d.ts',
    target: 'src/codegen/core-text.generated.ts',
    name: 'CORE_DTS',
    doc: 'The text of `core.d.ts`, the workflow SDK authoring declarations.',
  },
  {
    source: 'cookbook/examples',
    target: 'src/codegen/cookbook-text.generated.ts',
    name: 'COOKBOOK_EXAMPLES',
    doc: 'The example workflows, file name → text, written as `.sim/examples/<file>`: together one correct example of each common block.',
    files: { recursive: false, include: (file) => file.endsWith('.ts') },
  },
  {
    source: 'src/workspace',
    target: 'src/codegen/workspace-text.generated.ts',
    name: 'WORKSPACE_SDK_DTS',
    doc: 'The workspace declaration SDK, file name → text (`index.d.ts` re-exports the rest).',
    files: { recursive: false, include: (file) => file.endsWith('.d.ts') },
  },
  {
    source: 'cookbook/workspace',
    target: 'src/codegen/workspace-cookbook-text.generated.ts',
    name: 'WORKSPACE_COOKBOOK',
    doc: 'The example workspace directory, path → text: one resource of each kind and a workflow using them.',
    files: { recursive: true, include: () => true },
  },
]

/**
 * `value` as a TypeScript literal. Single quotes are written as `\u0027` so embedded source, such
 * as a `.d.ts` re-exporting `'./file'`, never reads as one of this module's own imports.
 */
function literal(value: unknown): string {
  return JSON.stringify(value).replaceAll("'", '\\u0027')
}

const checkOnly = process.argv.includes('--check')
const stale: string[] = []

for (const { source, target, name, doc, files } of EMBEDDED) {
  const absolute = path.join(packageRoot, source)
  const declaration = files
    ? `export const ${name}: Readonly<Record<string, string>> = ${literal(embeddedFolderTexts(absolute, files))}`
    : `export const ${name} = ${literal(readFileSync(absolute, 'utf8'))}`
  const text = [
    `// Generated by scripts/generate-embedded-text.ts from ${source}; do not edit.`,
    '',
    `/** ${doc} */`,
    declaration,
    '',
  ].join('\n')
  const output = path.join(packageRoot, target)
  if (!checkOnly) writeFileSync(output, text)
  else if (!existsSync(output) || readFileSync(output, 'utf8') !== text) stale.push(target)
}

if (stale.length > 0) {
  console.error(
    `✗ stale in packages/workflow-sdk: ${stale.join(', ')}. Run \`bun run generate:workflow-sdk-embedded-text\` and commit the result.`
  )
  process.exit(1)
}
if (checkOnly) console.log('✓ the workflow SDK embedded text is current')
