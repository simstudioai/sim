/**
 * Embeds the files a bundled consumer such as the CLI writes into a source directory without the
 * package on disk, each as a string in `src/codegen/*.generated.ts`: `src/core.d.ts` as `CORE_DTS`
 * (the authoring declarations) and `cookbook/workflow.ts` as `COOKBOOK_TS` (the example
 * workflow). `core-text.test.ts` and `cookbook-text.test.ts` fail when either drifts.
 *
 *   bun scripts/generate-embedded-text.ts && bunx biome check --write src/codegen
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')

const EMBEDDED = [
  {
    source: 'src/core.d.ts',
    target: 'src/codegen/core-text.generated.ts',
    name: 'CORE_DTS',
    doc: 'The text of `core.d.ts`, the workflow SDK authoring declarations.',
  },
  {
    source: 'cookbook/workflow.ts',
    target: 'src/codegen/cookbook-text.generated.ts',
    name: 'COOKBOOK_TS',
    doc: 'The text of `cookbook/workflow.ts`: one correct example of each common block.',
  },
]

for (const { source, target, name, doc } of EMBEDDED) {
  const text = readFileSync(path.join(packageRoot, source), 'utf8')
  writeFileSync(
    path.join(packageRoot, target),
    [
      `// Generated by scripts/generate-embedded-text.ts from ${source}; do not edit.`,
      '',
      `/** ${doc} */`,
      `export const ${name} = ${JSON.stringify(text)}`,
      '',
    ].join('\n')
  )
}
