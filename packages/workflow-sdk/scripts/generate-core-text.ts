/**
 * Embeds `src/core.d.ts` as a string (`CORE_DTS` in `src/codegen/core-text.generated.ts`), so a
 * bundled consumer such as the CLI can write the authoring declarations next to the generated
 * block types without the package on disk. `core-text.test.ts` fails when the two drift.
 *
 *   bun scripts/generate-core-text.ts && bunx biome check --write src/codegen
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')
const text = readFileSync(path.join(packageRoot, 'src', 'core.d.ts'), 'utf8')

writeFileSync(
  path.join(packageRoot, 'src', 'codegen', 'core-text.generated.ts'),
  [
    '// Generated by scripts/generate-core-text.ts from src/core.d.ts; do not edit.',
    '',
    '/** The text of `core.d.ts`, the workflow SDK authoring declarations. */',
    `export const CORE_DTS = ${JSON.stringify(text)}`,
    '',
  ].join('\n')
)
