/**
 * Embeds the workspace declaration SDK (`src/workspace/*.d.ts`) as strings
 * (`WORKSPACE_SDK_DTS` in `src/codegen/workspace-text.generated.ts`) and the example workspace
 * directory (`cookbook/workspace/**` as `WORKSPACE_COOKBOOK` in
 * `src/codegen/workspace-cookbook-text.generated.ts`), so a bundled consumer such as the CLI can
 * write them into a workspace source directory without the package on disk.
 * `workspace-text.test.ts` fails when either drifts.
 *
 *   bun scripts/generate-workspace-text.ts && bunx biome check --write src/codegen
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')
const dir = path.join(packageRoot, 'src', 'workspace')
const files = Object.fromEntries(
  readdirSync(dir)
    .filter((name) => name.endsWith('.d.ts'))
    .sort()
    .map((name) => [name, readFileSync(path.join(dir, name), 'utf8')])
)

writeFileSync(
  path.join(packageRoot, 'src', 'codegen', 'workspace-text.generated.ts'),
  [
    '// Generated by scripts/generate-workspace-text.ts from src/workspace/*.d.ts; do not edit.',
    '',
    '/** The workspace declaration SDK, file name → text (`index.d.ts` re-exports the rest). */',
    `export const WORKSPACE_SDK_DTS: Readonly<Record<string, string>> = ${JSON.stringify(files)}`,
    '',
  ].join('\n')
)

const cookbookDir = path.join(packageRoot, 'cookbook', 'workspace')
const cookbook = Object.fromEntries(
  readdirSync(cookbookDir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(cookbookDir, path.join(entry.parentPath, entry.name)))
    .map((file) => file.split(path.sep).join('/'))
    .sort()
    .map((file) => [file, readFileSync(path.join(cookbookDir, file), 'utf8')])
)

writeFileSync(
  path.join(packageRoot, 'src', 'codegen', 'workspace-cookbook-text.generated.ts'),
  [
    '// Generated by scripts/generate-workspace-text.ts from cookbook/workspace; do not edit.',
    '',
    '/** The example workspace directory, path → text: one resource of each kind and a workflow using them. */',
    `export const WORKSPACE_COOKBOOK: Readonly<Record<string, string>> = ${JSON.stringify(cookbook)}`,
    '',
  ].join('\n')
)
