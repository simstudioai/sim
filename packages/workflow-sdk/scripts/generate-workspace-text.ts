/**
 * Embeds the workspace declaration SDK (`src/workspace/*.d.ts`) as strings
 * (`WORKSPACE_SDK_DTS` in `src/codegen/workspace-text.generated.ts`), so a bundled consumer such
 * as the CLI can write it into a workspace source directory without the package on disk.
 * `workspace-text.test.ts` fails when the two drift.
 *
 *   bun scripts/generate-workspace-text.ts && bunx biome check --write src/codegen
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')
const dir = path.join(packageRoot, 'src', 'workspace')
const files = Object.fromEntries(
  readdirSync(dir)
    .filter((name) => name.endsWith('.d.ts'))
    .sort()
    .map((name) => [name, readFileSync(path.join(dir, name), 'utf8')])
)

writeFileSync(
  path.join(packageRoot, 'src', 'codegen', 'workspace-text.generated.ts'),
  [
    '// Generated by scripts/generate-workspace-text.ts from src/workspace/*.d.ts; do not edit.',
    '',
    '/** The workspace declaration SDK, file name → text (`index.d.ts` re-exports the rest). */',
    `export const WORKSPACE_SDK_DTS: Readonly<Record<string, string>> = ${JSON.stringify(files)}`,
    '',
  ].join('\n')
)
