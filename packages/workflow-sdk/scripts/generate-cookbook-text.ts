/**
 * Embeds `cookbook/workflow.ts` as a string (`COOKBOOK_TS` in
 * `src/codegen/cookbook-text.generated.ts`), so a bundled consumer such as the CLI can write the
 * example workflow next to the generated block types without the package on disk.
 * `cookbook-text.test.ts` fails when the two drift.
 *
 *   bun scripts/generate-cookbook-text.ts && bunx biome check --write src/codegen
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const packageRoot = path.resolve(import.meta.dirname, '..')
const text = readFileSync(path.join(packageRoot, 'cookbook', 'workflow.ts'), 'utf8')

writeFileSync(
  path.join(packageRoot, 'src', 'codegen', 'cookbook-text.generated.ts'),
  [
    '// Generated by scripts/generate-cookbook-text.ts from cookbook/workflow.ts; do not edit.',
    '',
    '/** The text of `cookbook/workflow.ts`: one correct example of each common block. */',
    `export const COOKBOOK_TS = ${JSON.stringify(text)}`,
    '',
  ].join('\n')
)
