import { PLANEV2RELEASES6E73E7_OUTPUT } from '@/tools/plane/outputs'
import { planeV2Releases6e73e7Schema } from '@/tools/plane/schemas'
import type {
  PlaneGetReleaseChangelogParams,
  PlaneGetReleaseChangelogResponse,
} from '@/tools/plane/types'
import {
  assertPlaneVersionFields,
  PLANE_CREDENTIAL_PARAMS,
  PLANE_VERSION_PARAM,
  planeApiUrl,
  planeApiVersion,
  planeHeaders,
  planeObjectResponse,
  planeRedirectPolicy,
} from '@/tools/plane/utils'
import type { ToolConfig } from '@/tools/types'
import { safeUrlPathSegment } from '@/tools/url-path'

export const planeGetReleaseChangelogTool: ToolConfig<
  PlaneGetReleaseChangelogParams,
  PlaneGetReleaseChangelogResponse
> = {
  id: 'plane_get_release_changelog',
  name: 'Plane Get a release changelog',
  description: 'Get a release changelog in Plane. Supports API v1 compatibility.',
  version: '1.0.0',
  params: {
    ...PLANE_CREDENTIAL_PARAMS,
    apiVersion: PLANE_VERSION_PARAM,
    workspace_slug: {
      type: 'string',
      required: true,
      visibility: 'user-or-llm',
      description: 'Workspace slug from the Plane URL (for example, my-team).',
    },
    pk: {
      type: 'string',
      required: true,
      visibility: 'user-or-llm',
      description: 'The release changelog id.',
    },
  },
  request: {
    url: (params) => {
      const version = planeApiVersion(params.apiVersion, true)
      assertPlaneVersionFields(
        params,
        version === 'v1' ? ['workspace_slug', 'pk'] : ['workspace_slug', 'pk'],
        ['workspace_slug', 'pk'],
        version
      )
      return version === 'v1'
        ? planeApiUrl(
            params.baseUrl,
            `/api/v1/workspaces/${safeUrlPathSegment(params.workspace_slug, 'workspace_slug')}/releases/${safeUrlPathSegment(params.pk, 'pk')}/changelog/`
          )
        : planeApiUrl(
            params.baseUrl,
            `/api/v2/workspaces/${safeUrlPathSegment(params.workspace_slug, 'workspace_slug')}/releases/${safeUrlPathSegment(params.pk, 'pk')}/changelog/`
          )
    },
    method: 'GET',
    headers: (params) => planeHeaders(params.apiKey),
    redirectPolicy: planeRedirectPolicy,
    retry: { enabled: true, maxRetries: 3, retryIdempotentOnly: true },
  },
  transformResponse: async (response, params) =>
    planeApiVersion(params?.apiVersion, true) === 'v1'
      ? planeObjectResponse(response, planeV2Releases6e73e7Schema)
      : planeObjectResponse(response, planeV2Releases6e73e7Schema),
  outputs: { result: PLANEV2RELEASES6E73E7_OUTPUT },
}
