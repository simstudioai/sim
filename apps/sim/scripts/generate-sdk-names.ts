#!/usr/bin/env bun
/**
 * Maintains `apps/sim/blocks/sdk-names.json`, the frozen SDK builder names (build-spec decision 7),
 * and its runtime form `apps/sim/blocks/sdk-names.generated.ts`.
 *
 * A method name is public API the moment a workflow file uses it, so this generator only ever
 * ADDS: a new block gets a namespace, a new operation a method, a new trigger a trigger method,
 * and a new `oauthCredential` / `triggerCredentials` param its `credential` alias. An existing
 * name is never recomputed, so editing an option label cannot rename `slack.sendMessage`.
 *
 * The runtime module holds the same data as one JSON string parsed at load, never an imported
 * `.json`: an imported JSON file this size makes TypeScript infer a type for every entry, which
 * is the type-check cost the tool-metadata artifacts document (`tool-registry-boundary` skill).
 *
 * `--check` (run by `check:audits`) fails when the JSON lacks an entry the registry needs, when any
 * two things share a name (two namespaces, two methods or triggers in one block, or two params on
 * one surface after aliasing), or when the runtime module is stale.
 *
 * Usage:
 *   bun run apps/sim/scripts/generate-sdk-names.ts           # add missing names
 *   bun run apps/sim/scripts/generate-sdk-names.ts --check   # fail on drift or collisions
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { registrySdkNameSources } from '@/lib/workflows/code/catalog/registry-sources'
import {
  extendSdkNames,
  type SdkNamesFile,
  validateSdkNames,
} from '@/lib/workflows/code/catalog/sdk-names'

const NAMES_PATH = resolve(import.meta.dir, '../blocks/sdk-names.json')
const MODULE_PATH = resolve(import.meta.dir, '../blocks/sdk-names.generated.ts')

async function readNames(): Promise<SdkNamesFile> {
  const parsed = JSON.parse(await readFile(NAMES_PATH, 'utf8')) as Partial<SdkNamesFile>
  if (parsed.version !== 1 || typeof parsed.blocks !== 'object' || parsed.blocks === null) {
    throw new Error(`${NAMES_PATH} is not a version 1 sdk-names file`)
  }
  return { version: 1, blocks: parsed.blocks }
}

/** A single-quoted JS literal of `json`, escaped the way `sync-tool-metadata.ts` escapes. */
function toJsStringLiteral(json: string): string {
  const escaped = json
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
  return `'${escaped}'`
}

function renderModule(names: SdkNamesFile): string {
  return `// Generated by apps/sim/scripts/generate-sdk-names.ts from blocks/sdk-names.json — do not edit.
// Regenerate with: bun run generate:sdk-names

import type { SdkNamesFile } from '@/lib/workflows/code/catalog/sdk-names'

/** The frozen SDK builder names. */
export const SDK_NAMES: SdkNamesFile = JSON.parse(
  ${toJsStringLiteral(JSON.stringify(names))}
)
`
}

async function readModule(): Promise<string | null> {
  try {
    return await readFile(MODULE_PATH, 'utf8')
  } catch {
    return null
  }
}

const checkOnly = process.argv.includes('--check')
const existing = await readNames()
const sources = registrySdkNameSources()

if (checkOnly) {
  const issues = validateSdkNames(existing, sources)
  if ((await readModule()) !== renderModule(existing)) {
    issues.push('sdk-names.generated.ts is stale')
  }
  if (issues.length > 0) {
    console.error(
      `sdk-names.json is out of date or has collisions (${issues.length}). Run \`bun run generate:sdk-names\`; a collision needs a hand-picked name for the NEW entry, never a rename of an existing one.\n`
    )
    for (const issue of issues) console.error(`  ${issue}`)
    process.exit(1)
  }
  console.log(`sdk-names.json covers ${sources.length} blocks with no collisions.`)
} else {
  const { names, added } = extendSdkNames(existing, sources)
  const issues = validateSdkNames(names, sources)
  await writeFile(NAMES_PATH, `${JSON.stringify(names, null, 2)}\n`)
  await writeFile(MODULE_PATH, renderModule(names))
  console.log(`Added ${added.length} name(s) to sdk-names.json.`)
  if (issues.length > 0) {
    console.error(`Collisions remain (${issues.length}); resolve them by hand:`)
    for (const issue of issues) console.error(`  ${issue}`)
    process.exit(1)
  }
}
