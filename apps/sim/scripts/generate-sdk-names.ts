#!/usr/bin/env bun
/**
 * Maintains `apps/sim/blocks/sdk-names/<type>.json`, the frozen SDK builder names (one file per
 * block type), and their runtime form `apps/sim/blocks/sdk-names.generated.ts`.
 *
 * A method name is public API the moment a workflow file uses it, so this generator only ever
 * ADDS: a new block gets a namespace, a new operation a method, a new trigger a trigger method,
 * and a new `oauthCredential` / `triggerCredentials` param its `credential` alias. An existing
 * name is never recomputed, so editing an option label cannot rename `slack.sendMessage`.
 *
 * One file per block keeps integration PRs from touching a shared file: a new block adds a file,
 * a new operation adds a line to its block's file. The runtime module holds one line per block,
 * each a JSON string parsed at load, never an imported `.json`: imported JSON makes TypeScript
 * infer a type for every entry, which is the type-check cost the tool-metadata artifacts document
 * (`tool-registry-boundary` skill). Two PRs that add neighbouring blocks can still conflict on
 * that module; regenerating resolves it.
 *
 * `--check` (run by `check:audits`) fails when the files lack anything the generator would add
 * (credential aliases included), when any two things share a name (two namespaces, two methods or
 * triggers in one block, or two params on one surface after aliasing), when a file is not in the
 * generator's format, or when the runtime module is stale.
 *
 * Usage:
 *   bun run apps/sim/scripts/generate-sdk-names.ts           # add missing names
 *   bun run apps/sim/scripts/generate-sdk-names.ts --check   # fail on drift or collisions
 */
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compareStrings } from '@sim/utils/string'
import { registrySdkNameSources } from '@/lib/workflows/code/catalog/registry-sources'
import {
  extendSdkNames,
  type SdkNamesFile,
  validateSdkNames,
} from '@/lib/workflows/code/catalog/sdk-names'

type SdkNamesEntry = SdkNamesFile['blocks'][string]

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const NAMES_DIR = resolve(SCRIPT_DIR, '../blocks/sdk-names')
const MODULE_PATH = resolve(SCRIPT_DIR, '../blocks/sdk-names.generated.ts')
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

const renderEntry = (entry: SdkNamesEntry) => `${JSON.stringify(entry, null, 2)}\n`

/** Each block type's file text, keyed by type. */
async function readEntryFiles(): Promise<Map<string, string>> {
  const files = (await readdir(NAMES_DIR)).filter((file) => file.endsWith('.json'))
  const texts = new Map<string, string>()
  for (const file of files.sort(compareStrings)) {
    texts.set(file.slice(0, -'.json'.length), await readFile(resolve(NAMES_DIR, file), 'utf8'))
  }
  return texts
}

function parseNames(texts: Map<string, string>): SdkNamesFile {
  const blocks: Record<string, SdkNamesEntry> = {}
  for (const [type, text] of texts) blocks[type] = JSON.parse(text)
  return { version: 1, blocks }
}

/** A single-quoted JS literal of `json`, escaped the way `sync-tool-metadata.ts` escapes. */
function toJsStringLiteral(json: string): string {
  const escaped = json
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
  return `'${escaped}'`
}

function renderModule(names: SdkNamesFile): string {
  const lines = Object.keys(names.blocks)
    .sort(compareStrings)
    .map((type) => {
      const key = IDENTIFIER.test(type) ? type : toJsStringLiteral(type)
      return `  ${key}: ${toJsStringLiteral(JSON.stringify(names.blocks[type]))},`
    })
  return `// Generated by apps/sim/scripts/generate-sdk-names.ts from blocks/sdk-names/*.json — do not edit.
// Regenerate with: bun run generate:sdk-names (also the way to resolve a merge conflict here).

import type { SdkNamesFile } from '@/lib/workflows/code/catalog/sdk-names'

/** Each block type's frozen names as JSON, one block per line. */
const BLOCKS: Record<string, string> = {
${lines.join('\n')}
}

/** The frozen SDK builder names. */
export const SDK_NAMES: SdkNamesFile = {
  version: 1,
  blocks: Object.fromEntries(
    Object.entries(BLOCKS).map(([type, json]) => [type, JSON.parse(json)])
  ),
}
`
}

async function readModule(): Promise<string | null> {
  try {
    return await readFile(MODULE_PATH, 'utf8')
  } catch {
    return null
  }
}

const checkOnly = process.argv.includes('--check')
const files = await readEntryFiles()
const existing = parseNames(files)
const sources = registrySdkNameSources()

if (checkOnly) {
  const issues = validateSdkNames(existing, sources)
  for (const [type, text] of files) {
    if (text !== renderEntry(existing.blocks[type])) {
      issues.push(`sdk-names/${type}.json is not in the generated format`)
    }
  }
  if ((await readModule()) !== renderModule(existing)) {
    issues.push('sdk-names.generated.ts is stale')
  }
  if (issues.length > 0) {
    console.error(
      `blocks/sdk-names is out of date or has collisions (${issues.length}). Run \`bun run generate:sdk-names\`; a collision needs a hand-picked name for the NEW entry, never a rename of an existing one.\n`
    )
    for (const issue of issues) console.error(`  ${issue}`)
    process.exit(1)
  }
  console.log(`blocks/sdk-names covers ${sources.length} blocks with no collisions.`)
} else {
  const { names, added } = extendSdkNames(existing, sources)
  const issues = validateSdkNames(names, sources)
  await mkdir(NAMES_DIR, { recursive: true })
  for (const [type, entry] of Object.entries(names.blocks)) {
    const text = renderEntry(entry)
    if (files.get(type) !== text) await writeFile(resolve(NAMES_DIR, `${type}.json`), text)
  }
  await writeFile(MODULE_PATH, renderModule(names))
  console.log(`Added ${added.length} name(s) to blocks/sdk-names.`)
  if (issues.length > 0) {
    console.error(`Collisions remain (${issues.length}); resolve them by hand:`)
    for (const issue of issues) console.error(`  ${issue}`)
    process.exit(1)
  }
}
