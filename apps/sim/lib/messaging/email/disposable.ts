import { createLogger } from '@sim/logger'

const logger = createLogger('DisposableEmail')

let disposableDomains: Promise<ReadonlySet<string>> | undefined

/**
 * Loaded on first use rather than at import, so every server module that reaches the auth config
 * does not parse the list at startup to serve a check that only account creation runs. A failed
 * load is not cached, so the next signup retries it.
 */
function loadDisposableDomains(): Promise<ReadonlySet<string>> {
  disposableDomains ??= import('@/lib/messaging/email/disposable-email-domains.json').then(
    ({ default: domains }) => new Set(domains),
    (error: unknown) => {
      disposableDomains = undefined
      throw error
    }
  )
  return disposableDomains
}

/**
 * The lowercased domain of an address: the part after its last `@` (a quoted local part may
 * contain one), without the trailing dot of a fully qualified name. Empty when there is none.
 */
export function emailDomain(email: string): string {
  return email
    .slice(email.lastIndexOf('@') + 1)
    .trim()
    .toLowerCase()
    .replace(/\.$/, '')
}

/**
 * True when the email's domain, or any parent of it, is a known disposable or temporary inbox
 * provider (Mailinator, temp-mail services, …). The server-side gate on self-service account
 * creation. `quickValidateEmail` keeps its own short synchronous list because it also runs in
 * browser forms, where this list cannot ship.
 *
 * Fails open: if the list cannot load, the check logs and allows the signup, because refusing
 * every legitimate signup is worse than admitting a few throwaway ones.
 *
 * `disposable-email-domains.json` is generated by `scripts/generate-disposable-email-domains.ts`
 * from the curated CC0 blocklist at
 * https://github.com/disposable-email-domains/disposable-email-domains (the list PyPI uses), minus
 * every public suffix and the script's reviewed exemptions (forwarding relays, real providers).
 * The suffix filter is what makes the parent-domain match safe: a listed `msk.ru` would refuse
 * every organization registered under it.
 */
export async function isDisposableEmail(email: string | null | undefined): Promise<boolean> {
  if (!email?.includes('@')) return false
  const domain = emailDomain(email)
  if (!domain) return false

  const labels = domain.split('.')
  const candidates = labels.slice(0, -1).map((_, i) => labels.slice(i).join('.'))

  let domains: ReadonlySet<string>
  try {
    domains = await loadDisposableDomains()
  } catch (error) {
    logger.error('Disposable email list failed to load; allowing the signup', { error })
    return false
  }

  return candidates.some((candidate) => domains.has(candidate))
}
