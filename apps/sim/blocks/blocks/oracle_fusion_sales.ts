const STATUS_FIELDS: Record<string, string> = {
  lead: 'leadStatusCode',
  opportunity: 'opportunityStatusCode',
  activity: 'activityStatusCode',
  revenue: 'revenueStatusCode',
}

/** Runs after variable resolution. Never coerce identifiers through Number. */
function operationParams(params: Record<string, unknown>): Record<string, unknown> {
  const toolId =
    typeof params.operation === 'string' ? params.operation : 'oracle_fusion_sales_list_accounts'
  const operationName = toolId.slice('oracle_fusion_sales_'.length)
  const definition = ORACLE_FUSION_SALES_OPERATIONS[operationName]
  if (!definition) return {}
  const definitions = getOracleFusionSalesParams(operationName)
  const result: Record<string, unknown> = {}
  for (const [key, field] of Object.entries(definitions)) {
    const sourceKey = key === 'statusCode' ? STATUS_FIELDS[definition.entity] : key
    const value = params[sourceKey]
    // Empty canvas controls are not PATCH clears. Direct tool inputs can explicitly send null.
    if (value === undefined || value === null || value === '') continue
    if (field.type === 'number') {
      result[key] = typeof value === 'string' ? Number(value) : value
    } else if (field.type === 'boolean') {
      if (value === 'default') continue
      result[key] = value === 'true' ? true : value === 'false' ? false : value
    } else if (field.type === 'json' && typeof value === 'string') {
      try {
        result[key] = JSON.parse(value)
      } catch {
        throw new Error(`${key} must be valid JSON`)
      }
    } else result[key] = value
  }
  return result
}

