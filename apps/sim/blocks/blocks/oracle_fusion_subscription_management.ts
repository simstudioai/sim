/** Runs after variable resolution; empty canvas controls are not explicit PATCH clears. */
function operationParams(params: Record<string, unknown>): Record<string, unknown> {
  const toolId =
    typeof params.operation === 'string'
      ? params.operation
      : 'oracle_fusion_subscription_management_list_subscriptions'
  const name = toolId.slice('oracle_fusion_subscription_management_'.length)
  const operation = getOracleFusionSubscriptionOperation(name)
  const entity = ORACLE_FUSION_SUBSCRIPTION_ENTITIES[operation.entity]
  const definitions = getOracleFusionSubscriptionParams(name)
  const result: Record<string, unknown> = {}
  for (const [key, field] of Object.entries(definitions)) {
    const value = params[key]
    if (value === undefined || value === null || value === '') continue
    if (key === 'coveredLevelPuid' && entity.scope && params.billingScope !== 'covered_level') {
      continue
    }
    if (field.type === 'number') {
      result[key] = typeof value === 'string' ? Number(value) : value
    } else if (field.type === 'boolean') {
      if (value === 'default') continue
      result[key] = value === 'true' ? true : value === 'false' ? false : value
    } else {
      result[key] = value
    }
  }
  return result
}

