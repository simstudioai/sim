/** A limit whose label starts with "Bytes" is a byte count. */
function formatLimit(label: string, value: number): string {
  const formatted = value.toLocaleString('en-US')
  return label.startsWith('Bytes') ? `${formatted} bytes` : formatted
}

function buildLimits(errors: string[]): string {
  for (const [name, limits, labels] of [
    ['SOURCE_LIMITS', SOURCE_LIMITS, WORKFLOW_LIMIT_LABELS],
    ['WORKSPACE_SOURCE_LIMITS', WORKSPACE_SOURCE_LIMITS, WORKSPACE_LIMIT_LABELS],
  ] as const) {
    const unlabeled = Object.keys(limits).filter((key) => !(key in labels))
    if (unlabeled.length)
      errors.push(`${name} has limits with no docs label: ${unlabeled.join(', ')}`)
  }
  for (const key of Object.keys(WORKSPACE_SOURCE_LIMITS)) {
    const placed = LIMIT_GROUPS.slice(1).filter((group) => group.keys.includes(key)).length
    if (placed !== 1)
      errors.push(`WORKSPACE_SOURCE_LIMITS.${key} is in ${placed} limits groups, not 1`)
  }

  const lines: string[] = ['']
  for (const group of LIMIT_GROUPS) {
    lines.push(`### ${group.title}`, '', '| Limit | Value |', '| --- | --- |')
    for (const key of group.keys) {
      lines.push(
        `| ${cell(group.labels[key])} | ${formatLimit(group.labels[key], group.limits[key])} |`
      )
    }
    lines.push('')
  }
  return lines.join('\n')
}

function rewrite(region: Region, doc: string, content: string, file: string): string {
  const begin = doc.indexOf(beginMarker(region))
  const end = doc.indexOf(endMarker(region))
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(`workflow-code-docs: ${region} markers not found in ${file}`)
  }
  return `${doc.slice(0, begin + beginMarker(region).length)}\n${content}\n${doc.slice(end)}`
}

function walkMdx(dir: string): string[] {
  return fs
    .readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter((entry) => entry.endsWith('.mdx'))
    .map((entry) => path.join(dir, entry))
}

/** A generated region, which the owners already check, so stale rows never block regenerating it. */
const GENERATED_REGION =
  /\{\/\* workflow-code-docs:[\w-]+:begin[\s\S]*?\{\/\* workflow-code-docs:[\w-]+:end \*\/\}/g

function checkProse(errors: string[]): void {
  const known = new Set<string>([...DIAGNOSTIC_CODES, ...WORKSPACE_DIAGNOSTIC_CODES])
  for (const file of walkMdx(PAGES_DIR)) {
    const rel = path.relative(rootDir, file)
    const text = fs.readFileSync(file, 'utf8')
    const prose = text.replace(GENERATED_REGION, '')
    for (const match of prose.matchAll(/`([EWI]_[A-Z0-9_]+)`/g)) {
      if (!known.has(match[1])) errors.push(`${rel} names ${match[1]}, which no engine emits`)
    }
  }
  const pinned = /typescript@(\d+\.\d+\.\d+)/.exec(typecheckCommand())?.[1]
  if (!pinned) {
    errors.push('typecheckCommand() no longer names a typescript@x.y.z release')
    return
  }
  for (const file of walkMdx(DOCS_DIR)) {
    for (const match of fs.readFileSync(file, 'utf8').matchAll(/typescript@(\d+\.\d+\.\d+)/g)) {
      if (match[1] !== pinned) {
        errors.push(
          `${path.relative(rootDir, file)} pins typescript@${match[1]}, but the CLI type-checks with ${pinned}`
        )
      }
    }
  }
}

function main(): void {
  const checkMode = process.argv.includes('--check')
  const errors: string[] = []
  const generated: Record<Region, string> = {
    'exit-codes': buildExitCodes(),
    diagnostics: buildDiagnostics(errors),
    limits: buildLimits(errors),
    'directory-kinds': buildDirectoryKinds(),
  }
  checkProse(errors)

  const writes: Array<{ rel: string; file: string; next: string }> = []
  for (const region of Object.keys(REGIONS) as Region[]) {
    const file = path.join(PAGES_DIR, REGIONS[region])
    const rel = path.relative(rootDir, file)
    if (!fs.existsSync(file)) {
      errors.push(`${rel} does not exist`)
      continue
    }
    const doc = fs.readFileSync(file, 'utf8')
    const next = rewrite(region, doc, generated[region], rel)
    if (next !== doc) writes.push({ rel, file, next })
  }

  if (errors.length > 0) {
    console.error('workflow-code-docs:')
    for (const error of [...new Set(errors)].sort(compareStrings)) console.error(`  - ${error}`)
    process.exit(1)
  }
  if (checkMode) {
    if (writes.length > 0) {
      console.error(
        `workflow-code-docs: out of date: ${writes.map((write) => write.rel).join(', ')}. Run \`bun run generate:workflow-code-docs\`.`
      )
      process.exit(1)
    }
    console.log('workflow-code-docs: up to date.')
    return
  }
  for (const { rel, file, next } of writes) {
    fs.writeFileSync(file, next)
    console.log(`workflow-code-docs: updated ${rel}`)
  }
}

main()
