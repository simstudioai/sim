import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compareStrings } from '@sim/utils/string'
import {
  type SourceCommandGroup,
  sourceExitCodeRows,
} from '../packages/sim-cli/src/commands/protocol/source-exit-codes'
import { DIAGNOSTIC_CODES } from '../packages/workflow-code/src/diagnostics/codes'
import { SOURCE_LIMITS } from '../packages/workflow-code/src/limits'
import { typecheckCommand } from '../packages/workflow-sdk/src/codegen/tsconfig'
import { WORKSPACE_DIAGNOSTIC_CODES } from '../packages/workspace-code/src/diagnostics/codes'
import { APPLY_ORDER } from '../packages/workspace-code/src/kind'
import { WORKSPACE_SOURCE_LIMITS } from '../packages/workspace-code/src/limits'
import { WORKSPACE_KIND_SPECS } from '../packages/workspace-code/src/specs'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DOCS_DIR = path.join(rootDir, 'apps/docs/content/docs')
const PAGES_DIR = path.join(DOCS_DIR, 'workflows/code')
const SYNTAX_PATH = path.join(rootDir, 'packages/workflow-code/src/compile/SYNTAX.md')
const WORKSPACE_CODES_PATH = path.join(rootDir, 'packages/workspace-code/src/diagnostics/codes.ts')

const REGIONS = {
  'exit-codes': 'exit-codes.mdx',
  diagnostics: 'diagnostics.mdx',
  limits: 'limits.mdx',
  'directory-kinds': 'directory.mdx',
} as const
type Region = keyof typeof REGIONS

const beginMarker = (region: Region) =>
  `{/* workflow-code-docs:${region}:begin — generated by \`bun run generate:workflow-code-docs\`; do not edit between markers */}`
const endMarker = (region: Region) => `{/* workflow-code-docs:${region}:end */}`

/** Text safe for MDX prose: braces and angle brackets escaped outside code spans. */
function mdx(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part.replaceAll('{', '\\{').replaceAll('}', '\\}').replaceAll('<', '&lt;')
    )
    .join('')
}

/** A TSDoc body as one line of prose: `{@link X}` becomes `X`, a hard wrap becomes a space. */
function tsdocText(lines: string[]): string {
  return lines
    .map((line) => line.replace(/^\s*\*\s?/, '').trim())
    .filter(Boolean)
    .join(' ')
    .replace(/\{@link ([^}]+)\}/g, '`$1`')
    .trim()
}

function cell(text: string): string {
  return mdx(text.replaceAll('\n', ' ')).replaceAll('|', '\\|')
}

const indent = (block: string, spaces: number) =>
  block
    .split('\n')
    .map((line) => (line ? ' '.repeat(spaces) + line : line))
    .join('\n')

function exitCodeTable(group: SourceCommandGroup): string {
  return [
    '| Code | Meaning | What to do |',
    '| --- | --- | --- |',
    ...sourceExitCodeRows(group).map(
      ({ code, meaning, next }) => `| \`${code}\` | ${cell(meaning)} | ${cell(next)} |`
    ),
  ].join('\n')
}

function buildExitCodes(): string {
  return [
    '',
    "<Tabs items={['Workflow directory', 'Workspace directory']}>",
    '  <Tab>',
    '',
    indent(exitCodeTable('sim workflows source'), 4),
    '',
    '  </Tab>',
    '  <Tab>',
    '',
    indent(exitCodeTable('sim workspaces source'), 4),
    '',
    '  </Tab>',
    '</Tabs>',
    '',
  ].join('\n')
}

interface DiagnosticRow {
  codes: string[]
  meaning: string
}
interface DiagnosticGroup {
  title: string
  note: string
  rows: DiagnosticRow[]
}

/** The groups of the Diagnostics section of SYNTAX.md: a bold title, then a table of code rows. */
function parseWorkflowDiagnostics(): DiagnosticGroup[] {
  const syntax = fs.readFileSync(SYNTAX_PATH, 'utf8')
  const start = syntax.indexOf('\n## Diagnostics')
  if (start === -1) throw new Error('SYNTAX.md has no "## Diagnostics" section')
  const groups: DiagnosticGroup[] = []
  let heading: string[] | null = null
  let current: DiagnosticGroup | null = null
  for (const line of syntax.slice(start).split('\n').slice(2)) {
    if (line.startsWith('**')) {
      heading = [line]
      continue
    }
    if (heading && line.trim() !== '') {
      heading.push(line)
      continue
    }
    if (heading) {
      const text = heading.join(' ')
      const match = /^\*\*(.+?)\*\*\s*(.*)$/.exec(text)
      if (!match) throw new Error(`Cannot read the SYNTAX.md diagnostics heading: ${text}`)
      current = { title: match[1], note: match[2].replace(/^\((.*)\)$/, '$1'), rows: [] }
      groups.push(current)
      heading = null
      continue
    }
    const row = /^\| (`[EWI]_[A-Z0-9_]+`(?:, `[EWI]_[A-Z0-9_]+`)*) \| (.*) \|$/.exec(line)
    if (row && current) {
      current.rows.push({
        codes: row[1].split(', ').map((code) => code.slice(1, -1)),
        meaning: row[2].replaceAll('\\|', '|'),
      })
    }
  }
  return groups
}

interface WorkspaceCodeGroup {
  title: string
  rows: DiagnosticRow[]
}

/**
 * The `const X_CODES = [...]` arrays of the workspace codes file: the TSDoc above an array is the
 * group's title and the TSDoc above each string is that code's meaning.
 */
function parseWorkspaceDiagnostics(): { groups: WorkspaceCodeGroup[]; undocumented: string[] } {
  const lines = fs.readFileSync(WORKSPACE_CODES_PATH, 'utf8').split('\n')
  const groups: WorkspaceCodeGroup[] = []
  const undocumented: string[] = []
  let doc: string[] = []
  let inDoc = false
  let groupTitle: string | null = null
  let current: WorkspaceCodeGroup | null = null
  let sharedLine = false
  for (const line of lines) {
    const trimmed = line.trim()
    if (inDoc) {
      if (trimmed.endsWith('*/')) {
        inDoc = false
        const body = trimmed.replace(/\*\/$/, '').trim()
        if (body && body !== '*') doc.push(body)
      } else doc.push(trimmed)
      continue
    }
    if (trimmed.startsWith('/**')) {
      doc = []
      const rest = trimmed.replace(/^\/\*\*/, '')
      if (rest.endsWith('*/')) doc.push(rest.replace(/\*\/$/, '').trim())
      else {
        inDoc = true
        if (rest.trim()) doc.push(rest.trim())
      }
      continue
    }
    const arrayStart = /^const ([A-Z_]+_CODES) = \[/.exec(trimmed)
    if (arrayStart) {
      sharedLine = arrayStart[1] === 'SHARED_CODES' || arrayStart[1] === 'OWN_CODES'
      current = null
      if (!sharedLine) {
        groupTitle = tsdocText(doc).replace(/\.$/, '')
        current = { title: groupTitle, rows: [] }
        groups.push(current)
      }
      doc = []
      continue
    }
    if (trimmed.startsWith(']')) {
      current = null
      continue
    }
    const code = /^'([EWI]_[A-Z0-9_]+)',?$/.exec(trimmed)
    if (code && current) {
      const meaning = tsdocText(doc)
      if (!meaning) undocumented.push(code[1])
      current.rows.push({ codes: [code[1]], meaning })
      doc = []
    } else if (trimmed !== '' && !trimmed.startsWith('//')) {
      doc = []
    }
  }
  return { groups, undocumented }
}

const codeCell = (codes: string[]) => codes.map((code) => `\`${code}\``).join(', ')

function diagnosticTable(rows: DiagnosticRow[]): string {
  return [
    '| Code | Meaning |',
    '| --- | --- |',
    ...rows.map(({ codes, meaning }) => `| ${codeCell(codes)} | ${cell(meaning)} |`),
  ].join('\n')
}

const WORKFLOW_GROUP_LEAD: Record<string, string> = {
  'Compile and print': 'Reading and writing `workflow.ts`.',
  'Lock and source meta': 'Reading `.sim/lock.json`. Each finding names a JSON `path`.',
  Canonicalize: 'Reading the stored workflow in a get.',
  Materialize: 'Matching the compiled file to the stored blocks.',
  Apply: 'Saving the workflow draft.',
}

/** One error per code `documented` names that `exported` does not hold, and per code it lacks. */
function codeDiff(
  what: string,
  documented: readonly string[],
  exported: readonly string[]
): string[] {
  const have = new Set(documented)
  const want = new Set(exported)
  const extra = documented.filter((code) => !want.has(code))
  const missing = exported.filter((code) => !have.has(code))
  return [
    ...(extra.length ? [`${what} names codes no engine emits: ${extra.join(', ')}`] : []),
    ...(missing.length ? [`${what} has no entry for: ${missing.join(', ')}`] : []),
  ]
}

function buildDiagnostics(errors: string[]): string {
  const workflow = parseWorkflowDiagnostics()
  const workflowRows = workflow.flatMap((group) => group.rows)
  const workflowMeaning = new Map(
    workflowRows.flatMap((row) => row.codes.map((code) => [code, row.meaning]))
  )
  for (const [what, documented, exported] of [
    ['SYNTAX.md Diagnostics', [...workflowMeaning.keys()], DIAGNOSTIC_CODES],
  ] as const) {
    errors.push(...codeDiff(what, documented, exported))
  }

  const { groups: workspace, undocumented } = parseWorkspaceDiagnostics()
  if (undocumented.length)
    errors.push(
      `workspace-code/src/diagnostics/codes.ts has no TSDoc for: ${undocumented.join(', ')}`
    )
  const ownCodes = new Set(workspace.flatMap((group) => group.rows.flatMap((row) => row.codes)))
  const exportedWorkspace: readonly string[] = WORKSPACE_DIAGNOSTIC_CODES
  errors.push(
    ...codeDiff(
      'workspace-code code arrays',
      [...ownCodes],
      exportedWorkspace.filter((code) => ownCodes.has(code) || !workflowMeaning.has(code))
    )
  )
  const shared: DiagnosticRow[] = exportedWorkspace
    .filter((code) => !ownCodes.has(code))
    .map((code) => ({ codes: [code], meaning: workflowMeaning.get(code) ?? '' }))

  const lines: string[] = ['', '### Workflow source', '']
  for (const group of workflow) {
    lines.push(`#### ${group.title}`, '')
    const lead = WORKFLOW_GROUP_LEAD[group.title]
    const note = lead ?? (group.note ? `${group.note}.` : '')
    if (!lead) errors.push(`No lead sentence for the diagnostics group "${group.title}"`)
    if (note) lines.push(mdx(note), '')
    lines.push(diagnosticTable(group.rows), '')
  }
  lines.push('### Workspace source', '')
  lines.push(
    'Workspace source reports every workflow code above for the files of `workflows/<key>/`, with that path as the file, and these codes for the rest of the directory.',
    ''
  )
  for (const group of workspace) {
    lines.push(`#### ${mdx(group.title)}`, '', diagnosticTable(group.rows), '')
  }
  lines.push(
    '#### Shared with workflow source',
    '',
    'A workspace finding with the same meaning as a workflow finding uses its code.',
    '',
    diagnosticTable(shared),
    ''
  )
  return lines.join('\n')
}

function buildDirectoryKinds(): string {
  return ['', ...APPLY_ORDER.map((kind) => `- ${mdx(WORKSPACE_KIND_SPECS[kind].guide)}`), ''].join(
    '\n'
  )
}

