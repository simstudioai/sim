/**
 * Generates the reference tables of the workflows-as-code docs from the code that owns them, so
 * the exit codes, diagnostic codes and limits a reader looks up can never drift from the CLI and
 * the engines:
 *
 * - `exit-codes`: `sourceExitCodeRows` (`packages/sim-cli/.../source-exit-codes.ts`), the one
 *   table `--help`, the generated CLI pages and `.sim/AGENTS.md` are already built from.
 * - `diagnostics`: the Diagnostics tables of `packages/workflow-code/src/compile/SYNTAX.md`
 *   (workflow codes) and the TSDoc of each code in `packages/workspace-code/src/diagnostics/codes.ts`
 *   (workspace codes), each set required to equal the code list the engines export.
 * - `directory-kinds`: the one line per resource kind (`WORKSPACE_KIND_SPECS[kind].guide`) that the
 *   workspace directory's `.sim/AGENTS.md` prints.
 * - `limits`: `SOURCE_LIMITS` and `WORKSPACE_SOURCE_LIMITS`. The values come from code; the label of
 *   each limit is authored here, and every limit must have one.
 *
 * Content is rewritten between the `workflow-code-docs:<region>` markers of the pages under
 * `apps/docs/content/docs/workflows/code/`. The check also fails on a diagnostic code a page
 * names that no engine emits, and on a `typescript@x.y.z` pin in the docs other than the release
 * the CLI type-checks a directory with.
 *
 * Usage:
 *   bun run scripts/sync-workflow-code-docs.ts           # write
 *   bun run scripts/sync-workflow-code-docs.ts --check   # fail on drift
 */

